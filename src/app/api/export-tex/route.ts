import { NextResponse } from 'next/server.js';
import JSZip from 'jszip';
import { validateProject, resolveVariant } from '@/lib/data';
import { renderLatex } from '@/lib/latex';

export const runtime = 'nodejs';
export const dynamic = 'force-dynamic';

export async function POST(req: Request) {
  try {
    const body = await req.json();
    if (!body || !body.project) {
      return NextResponse.json({ error: 'Missing project data' }, { status: 400 });
    }

    const project = validateProject(body.project);
    const variantId = typeof body.variantId === 'string' && body.variantId ? body.variantId : project.activeVariantId;
    const variant = project.variants.find((v) => v.id === variantId) ?? project.variants[0];
    const resolved = resolveVariant(project, variant);

    let latexSource = renderLatex(resolved);
    const zip = new JSZip();

    // Check if profile photo exists
    let hasPhoto = false;
    if (resolved.templateId === 't05-profile-cv' && resolved.profile.photoDataUrl) {
      const match = resolved.profile.photoDataUrl.match(/^data:image\/(png|jpeg);base64,(.+)$/);
      if (match) {
        hasPhoto = true;
        const ext = match[1] === 'jpeg' ? 'jpg' : 'png';
        const photoBuffer = Buffer.from(match[2], 'base64');
        zip.file(`assets/profile.${ext}`, photoBuffer);

        // Adjust main.tex to reference local assets/profile.ext if needed
        latexSource = latexSource.replace(/\\includegraphics\[.*?\]\{.*?\}/g, (orig) => {
          if (orig.includes('photo') || orig.includes('profile')) {
            return `\\includegraphics[width=26mm,height=26mm,keepaspectratio]{assets/profile.${ext}}`;
          }
          return orig;
        });
      }
    }

    // Add main.tex
    zip.file('main.tex', latexSource);

    // Add structured resume data backup
    zip.file('resume-data.json', JSON.stringify(project, null, 2));

    // Add README.md
    const safeName = resolved.profile.name.replace(/[^a-zA-Z0-9_-]/g, '_') || 'Resume';
    const readmeContent = `# ${resolved.profile.name} — Resume LaTeX Package

Generated by **Resume Studio** (Local-First Resume & CV Editor).

## Compilation Instructions

This standalone document compiles cleanly using standard TeX Live, MacTeX, MiKTeX, or Overleaf:

\`\`\`bash
pdflatex -interaction=nonstopmode -halt-on-error main.tex
\`\`\`

## Package Structure
- \`main.tex\`: Standalone, production-ready LaTeX source document.
- \`resume-data.json\`: Full versioned structured content backup.
${hasPhoto ? '- `assets/profile.*`: High-resolution local profile portrait.\n' : ''}
## Template & Preset Details
- Template: \`${resolved.templateId}\`
- Paper: \`${resolved.design.paper}\`
- Font Family: \`${resolved.design.fontFamily}\` (${resolved.design.fontSize}pt)
- Primary Accent: \`${resolved.design.accentColor}\`
`;
    zip.file('README.md', readmeContent);

    // Generate ZIP buffer
    const zipBuffer = await zip.generateAsync({
      type: 'nodebuffer',
      compression: 'DEFLATE',
      compressionOptions: { level: 9 },
    });

    const filename = `${safeName}_latex_package.zip`;

    return new Response(new Uint8Array(zipBuffer), {
      status: 200,
      headers: {
        'Content-Type': 'application/zip',
        'Content-Disposition': `attachment; filename="${filename}"`,
        'Cache-Control': 'no-store',
      },
    });
  } catch (err: unknown) {
    const message = err instanceof Error ? err.message : 'Failed to export LaTeX package';
    return NextResponse.json({ error: message }, { status: 500 });
  }
}
